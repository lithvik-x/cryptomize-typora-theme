#!/usr/bin/env python3
"""Assemble the CryptoMize Typora theme (cryptomize.css / cryptomize-dark.css).

Concatenates the generated brand tokens with the authored section files into two
standalone themes, bundles the Rajdhani faces, and runs integrity checks:
  python3 build.py          build + dangling-var check
  python3 build.py --check  also verify every token defined in the token files is
                            byte-present in the right dist file (V3-integrity)
"""
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "src"
DIST = ROOT / "dist"
ASSETS_OUT = DIST / "cryptomize-assets"

HEADER = """/*
CryptoMize Typora Theme — {mode} ("{label}").
(c) 2026 CryptoMize. Typography: Rajdhani (SIL OFL 1.1 — see cryptomize-assets/).
Palette derived from the CryptoMize brand design tokens; WCAG AA verified.
Generated by build.py — edit src/ and re-build instead of this file.
*/
"""

SECTION_ORDER = ["fonts.css", "shared.css", "codemirror.css", "alerts.css", "print.css"]

RAJDHANI = {400: "rajdhani-Regular.woff2", 500: "rajdhani-Medium.woff2",
            600: "rajdhani-SemiBold.woff2", 700: "rajdhani-Bold.woff2"}


def fonts_css():
    parts = ["/* [FONTS] — bundled faces (paths relative to the theme file). */"]
    for w, fname in sorted(RAJDHANI.items()):
        f = SRC / "assets" / fname
        assert f.exists() and f.read_bytes()[:4] == b"wOF2", f"missing Rajdhani {w}"
        parts.append(
            f'@font-face {{ font-family: "Rajdhani"; font-style: normal; font-weight: {w}; '
            f'font-display: swap; src: local("Rajdhani"), url("./cryptomize-assets/{fname}") format("woff2"); }}'
        )
    return "\n".join(parts) + "\n"


def used_vars(text):
    return set(re.findall(r"var\((--[A-Za-z0-9_-]+)", text))


def main():
    check = "--check" in sys.argv
    if DIST.exists():
        shutil.rmtree(DIST)
    ASSETS_OUT.mkdir(parents=True, exist_ok=True)
    for fname in RAJDHANI.values():
        (ASSETS_OUT / fname).write_bytes((SRC / "assets" / fname).read_bytes())
    lic = SRC / "assets" / "Rajdhani-OFL.txt"
    if not lic.exists():
        print("WARN: Rajdhani-OFL.txt missing from src/assets — required for redistribution")
    else:
        (ASSETS_OUT / "Rajdhani-OFL.txt").write_text(lic.read_text())

    tokens = {
        "light": (SRC / "tokens" / "light.css").read_text(),
        "dark": (SRC / "tokens" / "dark.css").read_text(),
    }
    sections = []
    for name in SECTION_ORDER:
        p = SRC / name
        sections.append(p.read_text() if p.exists() else f"/* [{name}] pending */")
    sections[0] = fonts_css()  # fonts generated, not authored

    ok = True
    for mode, fname, label in (("light", "cryptomize.css", "CryptoMize"), ("dark", "cryptomize-dark.css", "CryptoMize Dark")):
        body = [HEADER.format(mode=mode, label=label), tokens[mode]] + sections
        if mode == "dark":
            flip = "\n".join(("  " + ln) if ln.strip() else ln for ln in tokens["light"].splitlines())
            body.append(
                "/* [PRINT-FLIP] dark file: light tokens for ink-friendly print/export.\n"
                "   Delete this block for WYSIWYG dark export. */\n"
                "@media print {\n" + flip + "\n}\n"
            )
        out = "\n\n".join(body) + "\n"
        (DIST / fname).write_text(out)
        print(f"assembled dist/{fname}: {len(out):,} bytes")

        # integrity: every var() used must be defined; every token definition present verbatim
        text = (DIST / fname).read_text()
        defined = set(re.findall(r"(--[A-Za-z0-9_-]+)\s*:", text))
        unresolved = used_vars(text) - defined
        if unresolved:
            print(f"INTEGRITY FAIL [{fname}] unresolved vars: {sorted(unresolved)}")
            ok = False
        for m in re.finditer(r"(--[A-Za-z0-9_-]+):\s*([^;]+);", tokens[mode]):
            if f"{m.group(1)}: {m.group(2)};" not in text:
                print(f"INTEGRITY FAIL [{fname}] token not byte-present: {m.group(1)}")
                ok = False
                break

    for meta in ("cryptomize.meta.json", "cryptomize-dark.meta.json"):
        src_meta = SRC / "meta" / meta
        if src_meta.exists():
            (DIST / meta).write_text(src_meta.read_text())

    print("integrity:", "PASS" if ok else "FAIL")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()

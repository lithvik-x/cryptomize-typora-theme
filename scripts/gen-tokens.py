def lum(h):
    h = h.lstrip("#")
    r, g, b = [int(h[i : i + 2], 16) / 255 for i in (0, 2, 4)]
    f = lambda c: c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)


def ratio(fg, bg):
    l1, l2 = lum(fg), lum(bg)
    if l1 < l2:
        l1, l2 = l2, l1
    return (l1 + 0.05) / (l2 + 0.05)


def adjust(fg, bg, thr=4.5, darken=None):
    """Shift lightness in-hue until ratio(fg,bg) >= thr."""
    hh, ll, ss = colorsys.rgb_to_hls(*[int(fg.lstrip("#")[i : i + 2], 16) / 255 for i in (0, 2, 4)])
    if darken is None:
        darken = lum(bg) > 0.18
    l = ll
    for _ in range(90):
        r = ratio(hex_of(hh, l, ss), bg)
        if r >= thr:
            break
        l = l - 0.01 if darken else l + 0.01
        if not (0.02 < l < 0.98):
            break
    return hex_of(hh, min(max(l, 0.02), 0.98), ss)


def hex_of(h, l, s):
    r, g, b = colorsys.hls_to_rgb(h, l, s)
    return "#%02x%02x%02x" % (round(r * 255), round(g * 255), round(b * 255))


def rgb_triplet(hexstr):
    h = hexstr.lstrip("#")
    return f"{int(h[0:2], 16)}, {int(h[2:4], 16)}, {int(h[4:6], 16)}"



    t["--ink-dim"] = "#9aa3ae"
    t["--on-brand"] = B["on_red"]
    # brand
    t["--brand"] = B["red"]
    t["--brand-bright"] = B["red_bright"]
    t["--brand-deep"] = adjust(B["red"], paper, 6.5)  # deep fill red
    t["--brand-rgb"] = rgb_triplet(B["red"])
